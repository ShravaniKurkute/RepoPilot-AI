def _cosine_similarity(vec_a: List[float], vec_b: List[float]) -> float:
    """Computes cosine similarity between two float vectors."""
    if not vec_a or not vec_b or len(vec_a) != len(vec_b):
        return 0.0
    dot = sum(a * b for a, b in zip(vec_a, vec_b))
    norm_a = math.sqrt(sum(a * a for a in vec_a))
    norm_b = math.sqrt(sum(b * b for b in vec_b))
    if norm_a == 0.0 or norm_b == 0.0:
        return 0.0
    return max(0.0, min(1.0, dot / (norm_a * norm_b)))


def _score_keyword(query: str, symbol_name: Optional[str], file_path: str, content: str) -> float:
    """Computes lexical relevance score based on token and symbol matches."""
    q_tokens = [t.lower() for t in re.findall(r"\w+", query) if len(t) > 1]
    if not q_tokens:
        return 0.0

    score = 0.0
    s_lower = (symbol_name or "").lower()
    f_lower = file_path.lower()
    c_lower = content.lower()

    for token in q_tokens:
        # Exact symbol match (highest weight)
        if token == s_lower:
            score += 3.0
        elif token in s_lower:
            score += 1.5

        # Path match
        if token in f_lower:
            score += 1.0

        # Term frequency in content
        count = c_lower.count(token)
        if count > 0:
            score += min(2.0, math.log(1 + count))

    return score


class VectorStore:
    """Manages chunk persistence, pgvector similarity search, and keyword indexing."""

    def __init__(self, storage_root: Optional[Path] = None):
        if storage_root is not None:
            self.storage_root = storage_root.resolve()
        else:
            p = Path(settings.WORKSPACE_STORAGE_PATH)
            self.storage_root = p if p.is_absolute() else (Path.cwd() / p).resolve()

    def _get_index_file(self, repository_id: str) -> Path:
        """Returns path to local JSON index file for a repository."""
        repo_dir = self.storage_root / repository_id
        repo_dir.mkdir(parents=True, exist_ok=True)
        return repo_dir / "rag_index.json"

    def _load_local_chunks(self, repository_id: str) -> List[CodeChunk]:
        """Loads chunks from local workspace storage."""
        index_file = self._get_index_file(repository_id)
        if not index_file.exists():
            return []
        try:
            with open(index_file, "r", encoding="utf-8") as f:
                data = json.load(f)
            chunks_data = data.get("chunks", [])
            return [CodeChunk.model_validate(c) for c in chunks_data]
        except Exception as e:
            logger.error(f"Failed to load local RAG index for '{repository_id}': {e}")
            return []

    def _save_local_chunks(
        self, repository_id: str, chunks: List[CodeChunk], stats: Optional[dict] = None
    ) -> None:
        """Saves chunks atomically to local workspace storage."""
        index_file = self._get_index_file(repository_id)
        temp_file = index_file.with_suffix(".tmp")
        payload = {
            "repository_id": repository_id,
            "updated_at": datetime.now(timezone.utc).isoformat(),
            "stats": stats or {},
            "chunks": [c.model_dump() for c in chunks],
        }
        with open(temp_file, "w", encoding="utf-8") as f:
            json.dump(payload, f, indent=2)
        temp_file.replace(index_file)

    async def upsert_chunks(
        self,
        repository_id: str,
        chunks: List[CodeChunk],
        embedding_provider: BaseEmbeddingProvider,
        force_reindex: bool = False,
    ) -> Tuple[int, int]:
        """Indexes chunks with incremental hash-based embedding reuse.

        Args:
            repository_id: Target repository ID.
            chunks: Candidate chunks generated by chunker.
            embedding_provider: Embedding model provider.
            force_reindex: If True, regenerates all embeddings.

        Returns:
            Tuple of (new_embedded_count, cached_count).
        """
        # Step 1: Load existing chunks to find cached embeddings by content_hash
        t_cache = time.time()
        existing_chunks = self._load_local_chunks(repository_id)
        hash_to_embedding: Dict[str, List[float]] = {}
        if not force_reindex:
            for c in existing_chunks:
                if c.embedding:
                    hash_to_embedding[c.content_hash] = c.embedding

        # Step 2: Identify chunks requiring embedding generation
        chunks_to_embed: List[CodeChunk] = []
        final_chunks: List[CodeChunk] = []
        cached_count = 0

        for chunk in chunks:
            if not force_reindex and chunk.content_hash in hash_to_embedding:
                cached_chunk = chunk.model_copy(
                    update={"embedding": hash_to_embedding[chunk.content_hash]}
                )
                final_chunks.append(cached_chunk)
                cached_count += 1
            else:
                chunks_to_embed.append(chunk)

        new_embedded_count = len(chunks_to_embed)
        logger.info(
            "Chunk cache inspection completed in %.3fs for '%s': %d total chunks (%d cached reused, %d requiring new embeddings).",
            time.time() - t_cache,
            repository_id,
            len(chunks),
            cached_count,
            new_embedded_count,
        )

        # Step 3: Generate embeddings in batches for new/modified chunks
        if chunks_to_embed:
            t_embed = time.time()
            texts = [c.content for c in chunks_to_embed]
            embeddings = await embedding_provider.embed_batch(texts)
            for chunk, emb in zip(chunks_to_embed, embeddings):
                updated_chunk = chunk.model_copy(update={"embedding": emb})
                final_chunks.append(updated_chunk)
            logger.info(
                "Embedding generation phase completed in %.2fs: %d chunks embedded.",
                time.time() - t_embed,
                new_embedded_count,
            )

        # Step 4: Persist to local workspace storage
        t_local = time.time()
        stats = {
            "total_chunks": len(final_chunks),
            "new_embedded": new_embedded_count,
            "cached": cached_count,
            "embedding_model": embedding_provider.model_name,
            "dimension": embedding_provider.dimension,
            "indexed_at": datetime.now(timezone.utc).isoformat(),
        }
        self._save_local_chunks(repository_id, final_chunks, stats)
        logger.info(
            "Local index persistence completed in %.3fs: saved %d chunks to %s.",
            time.time() - t_local,
            len(final_chunks),
            self._get_index_file(repository_id),
        )

        # Step 5: Persist to PostgreSQL + pgvector if connection is active
        t_pg = time.time()
        await self._sync_to_postgres(repository_id, final_chunks)
        logger.info("PostgreSQL pgvector sync completed in %.3fs.", time.time() - t_pg)

        logger.info(
            f"Indexed repository '{repository_id}': {len(final_chunks)} total chunks "
            f"({new_embedded_count} new, {cached_count} cached)."
        )

        return new_embedded_count, cached_count

    async def _sync_to_postgres(
        self, repository_id: str, chunks: List[CodeChunk]
    ) -> None:
        """Syncs chunks into PostgreSQL + pgvector database if reachable."""
        is_connected = await check_database_connection()
        if not is_connected:
            return

        try:
            async with AsyncSessionLocal() as session:
                # Remove obsolete records for this repository to maintain strict isolation
                await session.execute(
                    delete(CodeChunkModel).where(
                        CodeChunkModel.repository_id == repository_id
                    )
                )

                # Batch insert models
                now = datetime.now(timezone.utc)
                models = [
                    CodeChunkModel(
                        id=c.chunk_id,
                        repository_id=c.repository_id,
                        file_path=c.file_path,
                        language=c.language,
                        symbol_name=c.symbol_name,
                        symbol_type=c.symbol_type,
                        start_line=c.start_line,
                        end_line=c.end_line,
                        associated_class_or_function=c.associated_class_or_function,
                        content=c.content,
                        content_hash=c.content_hash,
                        import_references=c.import_references,
                        metadata_json={},
                        embedding=c.embedding,
                        created_at=now,
                    )
                    for c in chunks
                ]
                session.add_all(models)
                await session.commit()
                logger.info(
                    f"Successfully synchronized {len(chunks)} chunks to PostgreSQL pgvector."
                )
        except Exception as e:
            logger.warning(
                f"Failed to synchronize chunks to PostgreSQL (local index remains active): {e}",
                exc_info=True,
            )

    async def search_vector(
        self,
        repository_id: str,
        query_vector: List[float],
        top_k: int = 10,
        language: Optional[str] = None,
        file_path: Optional[str] = None,
    ) -> List[SearchResultChunk]:
        """Performs dense vector similarity search against indexed chunks."""
        # Check PostgreSQL + pgvector first
        if await check_database_connection():
            try:
                pg_results = await self._search_postgres_vector(
                    repository_id, query_vector, top_k, language, file_path
                )
                if pg_results is not None:
                    return pg_results
            except Exception as e:
                logger.debug(f"pgvector query fallback: {e}")

        # Local vector search fallback
        chunks = self._load_local_chunks(repository_id)
        candidates = []

        for c in chunks:
            # Enforce repository isolation
            if c.repository_id != repository_id:
                continue
            if language and c.language.lower() != language.lower():
                continue
            if file_path and file_path.lower() not in c.file_path.lower():
                continue
            if not c.embedding:
                continue

            sim = _cosine_similarity(query_vector, c.embedding)
            candidates.append((sim, c))

        # Sort descending by cosine similarity
        candidates.sort(key=lambda x: x[0], reverse=True)

        results: List[SearchResultChunk] = []
        for sim, c in candidates[:top_k]:
            results.append(
                SearchResultChunk(
                    chunk_id=c.chunk_id,
                    file_path=c.file_path,
                    start_line=c.start_line,
                    end_line=c.end_line,
                    language=c.language,
                    symbol_name=c.symbol_name,
                    symbol_type=c.symbol_type,
                    associated_class_or_function=c.associated_class_or_function,
                    content=c.content,
                    relevance_score=round(sim, 4),
                    retrieval_method="semantic",
                    semantic_score=round(sim, 4),
                    keyword_score=None,
                )
            )

        return results

    async def _search_postgres_vector(
        self,
        repository_id: str,
        query_vector: List[float],
        top_k: int,
        language: Optional[str],
        file_path: Optional[str],
    ) -> Optional[List[SearchResultChunk]]:
        """Queries pgvector using native cosine distance (<=>)."""
        async with AsyncSessionLocal() as session:
            stmt = select(
                CodeChunkModel,
                (1.0 - CodeChunkModel.embedding.cosine_distance(query_vector)).label("similarity"),
            ).where(CodeChunkModel.repository_id == repository_id)

            if language:
                stmt = stmt.where(CodeChunkModel.language == language)
            if file_path:
                stmt = stmt.where(CodeChunkModel.file_path.ilike(f"%{file_path}%"))

            stmt = stmt.order_by(text("similarity DESC")).limit(top_k)
            rows = await session.execute(stmt)

            results: List[SearchResultChunk] = []
            for model, sim in rows:
                score = float(sim) if sim is not None else 0.0
                results.append(
                    SearchResultChunk(
                        chunk_id=model.id,
                        file_path=model.file_path,
                        start_line=model.start_line,
                        end_line=model.end_line,
                        language=model.language,
                        symbol_name=model.symbol_name,
                        symbol_type=model.symbol_type,
                        associated_class_or_function=model.associated_class_or_function,
                        content=model.content,
                        relevance_score=round(score, 4),
                        retrieval_method="semantic",
                        semantic_score=round(score, 4),
                        keyword_score=None,
                    )
                )
            return results

    async def search_keyword(
        self,
        repository_id: str,
        query_text: str,
        top_k: int = 10,
        language: Optional[str] = None,
        file_path: Optional[str] = None,
    ) -> List[SearchResultChunk]:
        """Performs lexical and identifier keyword search."""
        chunks = self._load_local_chunks(repository_id)
        candidates = []

        for c in chunks:
            # Enforce repository isolation
            if c.repository_id != repository_id:
                continue
            if language and c.language.lower() != language.lower():
                continue
            if file_path and file_path.lower() not in c.file_path.lower():
                continue

            score = _score_keyword(query_text, c.symbol_name, c.file_path, c.content)
            if score > 0.0:
                candidates.append((score, c))

        if not candidates:
            return []

        # Sort descending by keyword score
        candidates.sort(key=lambda x: x[0], reverse=True)
        max_score = candidates[0][0]

        results: List[SearchResultChunk] = []
        for raw_score, c in candidates[:top_k]:
            normalized_score = min(1.0, max(0.0, raw_score / max_score)) if max_score > 0 else 0.0
            results.append(
                SearchResultChunk(
                    chunk_id=c.chunk_id,
                    file_path=c.file_path,
                    start_line=c.start_line,
                    end_line=c.end_line,
                    language=c.language,
                    symbol_name=c.symbol_name,
                    symbol_type=c.symbol_type,
                    associated_class_or_function=c.associated_class_or_function,
                    content=c.content,
                    relevance_score=round(normalized_score, 4),
                    retrieval_method="keyword",
                    semantic_score=None,
                    keyword_score=round(raw_score, 4),
                )
            )

        return results

    async def delete_repository_index(self, repository_id: str) -> bool:
        """Deletes all indexed chunks for a repository from database and local storage."""
        # 1. Delete local file
        index_file = self._get_index_file(repository_id)
        if index_file.exists():
            index_file.unlink()

        # 2. Delete from PostgreSQL if connected
        if await check_database_connection():
            try:
                async with AsyncSessionLocal() as session:
                    await session.execute(
                        delete(CodeChunkModel).where(
                            CodeChunkModel.repository_id == repository_id
                        )
                    )
                    await session.commit()
            except Exception as e:
                logger.warning(f"Failed to clear PostgreSQL records for '{repository_id}': {e}")

        logger.info(f"Cleared RAG index for repository '{repository_id}'.")
        return True

    def get_stats(self, repository_id: str) -> IndexingStatsResponse:
        """Computes and returns indexing statistics for a repository."""
        chunks = self._load_local_chunks(repository_id)
        index_file = self._get_index_file(repository_id)

        distinct_files = {c.file_path for c in chunks}
        named_symbols = sum(1 for c in chunks if c.symbol_name)
        languages: Dict[str, int] = {}
        for c in chunks:
            languages[c.language] = languages.get(c.language, 0) + 1

        last_indexed_at = None
        if index_file.exists():
            try:
                with open(index_file, "r", encoding="utf-8") as f:
                    data = json.load(f)
                    last_indexed_at = data.get("updated_at")
            except Exception:
                pass

        return IndexingStatsResponse(
            repository_id=repository_id,
            total_chunks=len(chunks),
            total_files=len(distinct_files),
            total_symbols_indexed=named_symbols,
            languages=languages,
            embedding_dimension=settings.EMBEDDING_DIMENSION,
            embedding_model=settings.EMBEDDING_MODEL,
            last_indexed_at=last_indexed_at,
        )


